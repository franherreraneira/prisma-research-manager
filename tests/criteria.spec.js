import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import ExcelJS from 'exceljs';
test('criterios y palabras clave configurables visibles antes de las decisiones',async({page})=>{
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.getByRole('button',{name:'Configuración',exact:true}).click();
 await page.getByRole('button',{name:'Añadir criterio de inclusión',exact:true}).click();
 await page.getByRole('textbox',{name:'Criterio de inclusión',exact:true}).fill('Tecnología marina pertinente');
 await page.getByRole('textbox',{name:'Palabras clave de inclusión',exact:true}).fill('offshore wind; eólica marina; mar');
 await page.getByRole('textbox',{name:'Palabras clave de exclusión E1',exact:true}).fill('land-based wind; terrestrial');
 await page.getByRole('textbox',{name:'Palabras clave de exclusión E2',exact:true}).fill('fishing');
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 await page.locator('.record').first().click();
 const criteria=page.getByRole('region',{name:'Criterios para título y resumen',exact:true});
 await expect(criteria).toContainText('Tecnología marina pertinente');
 await expect(criteria).toContainText('offshore wind · detectada');
 await expect(criteria).toContainText('eólica marina · sin coincidencia');
 await expect(criteria).toContainText('mar · sin coincidencia');
 await expect(criteria).toContainText('fishing · detectada');
 await expect(criteria).toContainText('terrestrial · sin coincidencia');
 await expect(criteria.locator('.criteria-keyword.include')).toHaveCount(1);
 await expect(criteria.locator('.criteria-keyword.exclude')).toHaveCount(1);
 await expect(page.getByRole('region',{name:'Criterios para texto completo',exact:true})).toContainText('Tecnología marina pertinente');
 // Coincidencias contradictorias no cambian las decisiones existentes.
 await expect(page.locator('.decisions').first().getByRole('button',{name:'Incluir',exact:true})).toHaveClass(/chosen/);
 await criteria.getByRole('button',{name:'Editar criterios',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Configuración del proyecto',exact:true})).toBeVisible();
 const [backup]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Respaldo',exact:true}).click()]);
 const json=JSON.parse(await fs.readFile(await backup.path(),'utf8'));
 expect(json.projects[0].inclusionCriteria[0].keywords).toBe('offshore wind; eólica marina; mar');
 expect(json.projects[0].reasons[0].keywords).toBe('land-based wind; terrestrial');
 await page.locator('.nav').getByRole('button',{name:'Exportar',exact:true}).click();
 const [xlsx]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'XLSX',exact:true}).click()]);
 const wb=new ExcelJS.Workbook();await wb.xlsx.readFile(await xlsx.path());
 expect(wb.getWorksheet('Criterios').getRow(2).getCell(3).value).toBe('Inclusión');
 expect(wb.getWorksheet('Criterios').getRow(2).getCell(4).value).toBe('offshore wind; eólica marina; mar');
 await page.getByRole('button',{name:'Nueva revisión',exact:true}).click();await page.getByRole('button',{name:'Cribado',exact:true}).click();await page.getByRole('button',{name:'Nuevo registro',exact:true}).click();
 await expect(page.getByRole('region',{name:'Criterios para título y resumen',exact:true})).toContainText('No hay criterios de inclusión definidos');
});
