import {test,expect} from '@playwright/test';
test('selección filtrada, cancelación, eliminación múltiple y referencias duplicadas',async({page})=>{
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 const all=page.getByRole('checkbox',{name:'Seleccionar todos los resultados',exact:true});
 const remove=page.getByRole('button',{name:'Eliminar seleccionados',exact:true});
 await expect(page.locator('.record')).toHaveCount(12);
 await expect(remove).toBeDisabled();
 await page.getByRole('checkbox',{name:'Seleccionar registro: Offshore wind and coastal fishing communities: coupled interactions',exact:true}).first().check();
 await page.locator('.record').first().click();
 await expect(page.getByLabel('Título',{exact:true})).toHaveValue('Offshore wind and coastal fishing communities: coupled interactions');
 page.once('dialog',dialog=>dialog.dismiss());await remove.click();
 await expect(page.locator('.record')).toHaveCount(12);
 page.once('dialog',dialog=>dialog.accept());await remove.click();
 await expect(page.locator('.record')).toHaveCount(11);
 // The surviving duplicate becomes available for screening when its original is deleted.
 await page.locator('.record').filter({hasText:'Offshore wind and coastal fishing communities: coupled interactions'}).click();
 await expect(page.getByRole('combobox',{name:'Duplicado de',exact:true})).toHaveValue('');
 const search=page.getByPlaceholder('Buscar por título, autor, DOI o resumen…');
 await search.fill('Institutional coordination');
 await expect(page.locator('.record')).toHaveCount(2);
 await all.check();
 await expect(page.locator('.bulktools')).toContainText('2 seleccionados');
 await page.getByRole('button',{name:'Limpiar selección'}).click();
 await expect(remove).toBeDisabled();
 await all.check();
 await search.fill('Offshore');
 await expect(remove).toBeDisabled();
 await search.fill('Institutional coordination');await all.check();
 page.once('dialog',dialog=>dialog.accept());await remove.click();
 await expect(page.locator('.record')).toHaveCount(0);
 await search.fill('');await expect(page.locator('.record')).toHaveCount(9);
 await all.check();
 await page.getByRole('button',{name:'Nueva revisión'}).click();
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 await expect(remove).toBeDisabled();await expect(all).toBeDisabled();
 await page.locator('.projectchoose select').selectOption('demo-ses');
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 await expect(page.locator('.record')).toHaveCount(9);
 await expect(remove).toBeDisabled();
});
