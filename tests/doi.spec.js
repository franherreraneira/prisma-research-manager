import {test,expect} from '@playwright/test';
test('completa un DOI, conserva datos manuales y muestra errores',async({page})=>{
 let requests=0;
 await page.route('https://api.crossref.org/works/**',async route=>{requests++;if(route.request().url().includes('missing'))return route.fulfill({status:404,body:'{}'});await route.fulfill({json:{message:{title:['Artículo de prueba DOI'],author:[{given:'Ana',family:'Pérez'}],published:{'date-parts':[[2024]]},'container-title':['Revista de prueba'],abstract:'<jats:p>Resumen recuperado</jats:p>'}}})});
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.getByRole('button',{name:'Nueva revisión'}).click();
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 await page.getByRole('button',{name:'Nuevo registro',exact:true}).click();
 await page.getByLabel('DOI',{exact:true}).fill('https://doi.org/10.1234/example');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByLabel('Título',{exact:true})).toHaveValue('Artículo de prueba DOI');
 await expect(page.getByLabel('Autores',{exact:true})).toHaveValue('Ana Pérez');
 await expect(page.getByLabel('Año',{exact:true})).toHaveValue('2024');
 await expect(page.getByRole('textbox',{name:'Resumen',exact:true})).toHaveValue('Resumen recuperado');
 await expect(page.getByLabel('DOI',{exact:true})).toHaveValue('10.1234/example');
 await page.getByLabel('Título',{exact:true}).fill('Título manual');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('Datos recuperados');
 await expect(page.getByLabel('Título',{exact:true})).toHaveValue('Título manual');
 await page.getByRole('button',{name:'Nuevo registro',exact:true}).click();
 await page.getByLabel('DOI',{exact:true}).fill('10.1234/example');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByLabel('Duplicado de')).not.toHaveValue('');
 await page.getByLabel('DOI',{exact:true}).fill('incorrecto');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('DOI válido');
 expect(requests).toBe(3);
 await page.getByLabel('DOI',{exact:true}).fill('10.1234/missing');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('no encontrado');
 await expect(page.getByLabel('Título',{exact:true})).toHaveValue('Artículo de prueba DOI');
 await page.unroute('https://api.crossref.org/works/**');
 await page.route('https://api.crossref.org/works/**',route=>route.abort());
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('No se pudo conectar');
});

test('recupera abstract de OpenAlex cuando Crossref no lo incluye',async({page})=>{
 await page.route('https://api.crossref.org/works/**',route=>route.fulfill({json:{message:{title:['Título sin abstract'],author:[],published:{'date-parts':[[2024]]}}}}));
 let mode='found';
 await page.route('https://api.openalex.org/works/**',route=>{
 if(mode==='error')return route.abort();
 return route.fulfill({json:{doi:'https://doi.org/10.1234/abstract',abstract_inverted_index:mode==='found'?{'Un':[0],'abstract':[1],'con':[2],'palabras':[3,5],'repetidas':[4]}:null}});
 });
 await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
 await page.getByRole('button',{name:'Nueva revisión'}).click();
 await page.getByRole('button',{name:'Cribado',exact:true}).click();
 await page.getByRole('button',{name:'Nuevo registro',exact:true}).click();
 await page.getByLabel('DOI',{exact:true}).fill('10.1234/abstract');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 const summary=page.getByRole('textbox',{name:'Resumen',exact:true});
 await expect(summary).toHaveValue('Un abstract con palabras repetidas palabras');
 await expect(page.getByRole('status')).toContainText('Abstract recuperado de OpenAlex');
 await summary.fill('Abstract manual');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('Abstract recuperado');
 await expect(summary).toHaveValue('Abstract manual');
 mode='missing';await summary.fill('');
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('No se encontró abstract');
 await expect(summary).toHaveValue('');
 mode='error';
 await page.getByRole('button',{name:'Completar desde DOI'}).click();
 await expect(page.getByRole('status')).toContainText('vuelve a intentarlo');
 await expect(page.getByLabel('Título',{exact:true})).toHaveValue('Título sin abstract');
});
